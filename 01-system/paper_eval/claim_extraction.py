def extract_claims(
    paper_context: dict[str, Any] | None,
    evidences: list[Evidence],
    publication_year: int | None = None,
) -> list[ExtractedClaim]:
    'draw claim. Prioritize the use of explicit fields in the paper portrait, and use text positioning words to cover when fields are missing.\n\n    `source_evidence_id` always points to the real EV-*: the portrait field itself has no evidence ID.\n    Therefore, you must go back to the text to find the paragraph where this sentence is written. If you cannot find it, this claim will not be generated.'
    profile = (paper_context or {}).get("paper_profile") or {}
    if not isinstance(profile, dict):
        profile = {}
    theory = _theory_from_profile(profile)
    contexts = _ascii_terms(str(profile.get("boundary_conditions") or ""), limit=4)

    claims: list[ExtractedClaim] = []
    seen_types: dict[str, str] = {}   # claim_type -> Already used basis sentence to avoid repeating the same sentence into multiple claims

    for field_name, claim_type in PROFILE_CLAIM_FIELDS:
        text = _profile_text(profile, field_name)
        if not text:
            continue
        supports = evidence_support(evidences, claim_type, limit=1)
        if not supports:
            continue
        evidence, sentence = supports[0]
        if seen_types.get(claim_type) == sentence:
            continue
        seen_types[claim_type] = sentence
        claims.append(
            ExtractedClaim(
                claim_id=f"CLM-{len(claims) + 1:02d}",
                claim_type=claim_type,
                claim_text=text[:400],
                source_evidence_id=evidence.evidence_id,
                concepts=_concepts_for(claim_type, profile, evidence, sentence),
                theory=theory,
                mechanism=(_ascii_terms(sentence, limit=4) or [""])[0] if claim_type == MECHANISM_CLAIM else "",
                context="; ".join(contexts),
                publication_year=publication_year,
                extraction_source="paper_context",
                keywords_en=_keywords_for(claim_type, profile, evidence, sentence),
                confidence=0.8,
            )
        )

    # After drawing the portrait, please fill in the text again: there is no claim type corresponding to the expression in the portrait field (for example, no
    # mechanism field), as long as the text has a clear mechanism/boundary positioning word, add one.
    # Each category can be supplemented with at most one item to avoid wasting the search budget on repeated statements of the same category of claims.
    if claims:
        used_types = {claim.claim_type for claim in claims}
        for claim_type in CLAIM_TYPES:
            if claim_type in used_types:
                continue
            supports = evidence_support(evidences, claim_type, limit=1)
            if not supports:
                continue
            evidence, sentence = supports[0]
            claims.append(
                ExtractedClaim(
                    claim_id=f"CLM-{len(claims) + 1:02d}",
                    claim_type=claim_type,
                    claim_text=sentence[:400],
                    source_evidence_id=evidence.evidence_id,
                    concepts=_ascii_terms(sentence, limit=6),
                    theory=theory,
                    context="; ".join(contexts),
                    publication_year=publication_year,
                    extraction_source="evidence_markers",
                    keywords_en=_keywords_for(claim_type, profile, evidence, sentence),
                    confidence=0.5,
                )
            )

    # The bottom line when the portrait does not draw any claims (the portrait generation failed or the fields are all placeholders): only the positioning words in the text are drawn.
    if not claims:
        for claim_type in CLAIM_TYPES:
            supports = evidence_support(evidences, claim_type, limit=1)
            if not supports:
                continue
            evidence, sentence = supports[0]
            claims.append(
                ExtractedClaim(
                    claim_id=f"CLM-{len(claims) + 1:02d}",
                    claim_type=claim_type,
                    claim_text=sentence[:400],
                    source_evidence_id=evidence.evidence_id,
                    concepts=_ascii_terms(sentence, limit=6),
                    theory=theory,
                    context="; ".join(contexts),
                    publication_year=publication_year,
                    extraction_source="evidence_markers",
                    keywords_en=_keywords_for(claim_type, profile, evidence, sentence),
                    confidence=0.5,
                )
            )
    return claims


def publication_year_of(metadata: dict[str, Any] | None, publish_date: str | None = None) -> int | None:
    'The year the target paper was published. For time leakage control: prior literature must precede it.'
    text = str((metadata or {}).get("year") or "") or str(publish_date or "")
    match = re.search(r"(19|20)\d{2}", text)
    return int(match.group(0)) if match else None
