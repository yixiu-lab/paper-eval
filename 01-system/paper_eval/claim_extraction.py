'Claim Extractor: Extract key claims that require external literature comparison from the target paper.\n\nWhy can’t we directly search the entire paper: the search terms for the entire paper will be overwhelmed by the subject words, and the search results will be "field related"\nRather than "relevance that can falsify this innovative claim". So first break the paper into comparable claims, and then search them one by one.\n\nFive categories of claims (only these categories are selected, method/result judgments still mainly rely on internal evidence):\n\n- research_gap What does the author claim is missing from existing research?\n- novelty_claim What the author claims was first proposed/first discovered/first verified\n- theoretical_contribution What theory does the author claim to advance?\n- mechanism_claim What new mechanism of action does the author propose?\n- boundary_claim What theoretical boundaries or research situations the author has expanded\n\nEach claim must carry `source_evidence_id` - pointing to EV-* in the Evidence Repository of this article,\nIt cannot be a sentence generated by the model out of thin air. Claims that are not supported by the main text will not be generated (it is better to draw less claims than to make them up).'

