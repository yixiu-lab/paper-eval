# Claim text → extract useful English theory, mechanism, and setting terms for search.
# only accepts words with more than 3 letters: claim basis sentences often contain function words such as "are the first test this mechanism".
# Inclusion of
# will flood search terms and reordering lists with noise (the 2-letter "we/is/are" is particularly deadly).
ASCII_TERM_RE = re.compile(r"[A-Za-z][A-Za-z\-]{2,}")

# General academic words and function words that must be removed from the search vocabulary.
# Actual test: when the claim basis sentence is in English ("We develop a new mechanism in which perceived procedural justice
# mediates..."), the whole sentence will be included in the search terms such as "underlying/process/develop/new/which",
# And ​​each candidate abstract has these words - the rearrangement is flattened to "whoever has more words is ranked first", and the priori of the real same topic is ranked second.
